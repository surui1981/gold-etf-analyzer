def _site_category(site_name: str) -> str | None:
    """按站名**兜底**推断类别；不满足条件返回 None。

    最长匹配优先：readhub 的 ``siteName`` 常带后缀（如 ``"C114 通信网"``），
    子串包含即可命中，更长的站名压过更短的前缀。
    """
    site = (site_name or "").lower()
    if not site.strip():
        return None
    best_hint: str | None = None
    best_cat: str | None = None
    for hint, cat in _SITE_HINTS.items():
        if hint.lower() in site and (best_hint is None or len(hint) > len(best_hint)):
            best_hint, best_cat = hint, cat
    return best_cat


# ────────────── V0.109.0 短 ASCII 词的词边界表 ───────────────
# 只收「长度 <= 3 且纯 ASCII」的词。这类词子串误匹配率高，且集中在优先级
# 最高的财经词典里，误判代价最大。
# 边界定义：前后紧邻字符不得是 ASCII 字母。数字与汉字都算「可接受邻居」，
# 这样 "2026PE"（中文财经报道常见写法）与 "科创ETF" 仍能命中。
_BOUNDARY_KW_MAX_LEN = 3
_BOUNDARY_PATTERNS: dict[str, re.Pattern[str]] = {
    kw: re.compile(
        rf"(?<![a-z]){re.escape(kw.lower())}(?![a-z])",
    )
    for kw in (*_FINANCE_KW, *_TECH_KW, *_VC_KW, *_BIZ_KW)
    if kw.isascii() and len(kw) <= _BOUNDARY_KW_MAX_LEN
}


def _hit(text: str, keywords: tuple[str, ...]) -> bool:
    """text（小写后）是否包含 keywords 任意一个（小写匹配）。

    大小写不敏感；中文不受 case 影响，英文小写化后匹配。

    V0.109.0：**长度 <= 3 的纯 ASCII 词**改走词边界正则，防止子串误匹配。
    这个 bug 是 V0.108.0 上一版词典带来的放大效应——财经优先级最高，
    ``"PE" in "openai"`` 为真，于是**所有 OpenAI 新闻都被判成财经**。
    同类高危：``ETH ⊂ Ethiopia``、``GP ⊂ GPT``、``AI ⊂ Retail/Chain/Mail``。

    只对短 ASCII 词加边界，其余（长英文词 / 全部中文词）保持子串匹配：
    - ``"2026PE"`` 仍命中 PE（数字不算字母边界）——中文财经报道的常见写法
    - ``"科创ETF"`` 仍命中 ETF（汉字不算 ASCII 字母）
    - ``"OpenAI"`` / ``"Anthropic"`` 等长词不受影响，仍走子串
    """
    return any(
        _BOUNDARY_PATTERNS[kw].search(text) if kw in _BOUNDARY_PATTERNS else kw.lower() in text
        for kw in keywords
    )


def classify(title: str, summary: str, site_name: str) -> str:
    """按「内容优先、站名兜底」返回 5 类之一。

    Args:
        title: 新闻标题（可空；与 summary 一起构成内容信号）
        summary: 摘要（可空；readhub 上财经源经常为空）
        site_name: 来源站名（可空；**仅作兜底**，见 Note）

    Returns:
        5 类之一：「财经」/「科技」/「创投」/「商业」/「其他」。

    Note:
        **V0.109.1 起站名不再参与内容匹配**（此前站名与标题摘要混在一个
        文本里匹配，因财经优先级最高导致站名压过内容，实测 27.8% 的条目
        纯靠站名定类，灾难新闻被当成财经）。改为两段式：

        1. 内容优先——``title + summary`` 命中 4 类词典，优先级
           财经 > 科技 > 创投 > 商业
        2. 站名兜底——内容一条都没命中时，用 ``_SITE_HINTS`` 推断（覆盖
           摘要为空的优质源，这是 V0.108.0 白名单真正要解决的问题）
        3. 都落空 → 「其他」

        财经优先的理由：财经关键词与商业/创投有重叠（「估值」「收购」），
        且财经是用户最关心的类目，宁可让科技新闻掉进「其他」也不误标财经。
    """
    content = f"{title or ''} {summary or ''}".lower()
    if content.strip():
        for category, keywords in _CONTENT_DICT:
            if _hit(content, keywords):
                return category
    # 内容没命中 → 站名兜底（摘要为空的优质源走这条路）
    site_cat = _site_category(site_name)
    if site_cat is not None:
        return site_cat
    return "其他"
